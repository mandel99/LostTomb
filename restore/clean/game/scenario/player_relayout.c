void pharaoh_game_file_relayout_players(PharaohUpgradePlayerRecord players[2])
{
    for (uint32_t player = 0; player < 2; ++player) {
        uint8_t expanded[0x49d8];
        for (uint32_t i = 0; i < sizeof(fields)/sizeof(fields[0]); ++i) {
            if (fields[i].source < 0)
                memset(expanded + fields[i].destination, 0, fields[i].bytes);
            else
                memcpy(expanded + fields[i].destination,
                    players[player].bytes + fields[i].source, fields[i].bytes);
        }
        memcpy(players[player].bytes, expanded, sizeof(expanded));
    }
}
