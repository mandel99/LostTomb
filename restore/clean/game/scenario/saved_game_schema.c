void pharaoh_saved_game_schema_bind(PharaohChunkDescriptor descriptors[181],
    void *const destinations[181],
    const PharaohChunkMigrationRecord *message_migrations,
    const PharaohChunkMigrationRecord *event_migrations)
{
    for (uint32_t i = 0; i < 181; ++i) {
        descriptors[i].codec = shapes[i].codec;
        descriptors[i].destination = destinations[i];
        descriptors[i].element_size = shapes[i].size;
        descriptors[i].element_count = shapes[i].count;
        descriptors[i].migrations = i == 77 ? message_migrations :
            i == 136 ? event_migrations : NULL;
    }
}
