PharaohMissionSceneProgramData *pharaoh_mission_scene_program_create(
    const PharaohCampaignIndex *campaign,const uint32_t (*export_limits)[6])
{
    if(campaign==NULL || export_limits==NULL) return NULL;
    PharaohMissionSceneProgramData *d=malloc(sizeof(*d));
    if(d!=NULL) bind_program(d,campaign,export_limits);
    return d;
}
