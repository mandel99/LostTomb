void pharaoh_building_sound_bind_file(const PharaohBuildingSoundFileContext *c,
    int32_t bank,const char *filename,int32_t mode)
{
    PharaohBuildingSoundBank *const row=&c->banks[bank];
    if(mode==0)row->roam=pharaoh_sound_file_id_load(c->loader,filename);
    else if(mode==1&&(int32_t)row->effect_count<3) {
        const uint32_t id=pharaoh_sound_file_id_load(c->loader,filename);
        row->effects[row->effect_count]=id;
        ++row->effect_count;
    }
}

void pharaoh_building_sound_files_initialize(const PharaohBuildingSoundFileContext *c)
{
    for(int32_t i=0;i<PHARAOH_BUILDING_SOUND_BANK_COUNT;++i) {
        PharaohBuildingSoundBank *const row=&c->banks[i];
        row->effects[0]=UINT32_MAX;row->effects[1]=UINT32_MAX;
        row->effects[2]=UINT32_MAX;row->roam=UINT32_MAX;row->effect_count=0;
    }
    for(size_t i=0;i<sizeof(loads)/sizeof(loads[0]);++i)
        pharaoh_building_sound_bind_file(c,loads[i].bank,loads[i].filename,loads[i].mode);
}
