// Mechanical 32-bit argument forwarding, not replacement audio/video routines.
// Recovered call sites already pass float parameters as their original DWORD bits.
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const units=JSON.parse(await readFile(path.join(root,'units.json'),'utf8'));
const sources=await Promise.all(units.map(unit=>readFile(path.join(root,unit.file),'utf8')));
const symbols=[...new Set(sources.flatMap(source=>[...source.matchAll(/\b_(?:AIL_[A-Za-z0-9_]+|Bink[A-Za-z0-9_]+|Smack[A-Za-z0-9_]+)_\d+\b/g)].map(match=>'_'+match[0])))].sort();
const entries=symbols.map(symbol=>{
 const match=symbol.match(/^__(AIL_.+|Bink.+|Smack.+)_(\d+)$/);
 if(!match || Number(match[2])%4) throw new Error('Unrecognized media import '+symbol);
 const stem=match[1],bytes=Number(match[2]);
 return {symbol,identifier:symbol.slice(1),dll:stem.startsWith('AIL_')?'mss32.dll':stem.startsWith('Bink')?'binkw32.dll':'smackw32.dll',export:'_'+stem+'@'+bytes,words:bytes/4,callback:stem==='BinkOpenMiles'};
});
let header='/* Generated by tools/generate_media_bindings.mjs. */\n#ifndef RESTORE_MEDIA_BINDINGS_H\n#define RESTORE_MEDIA_BINDINGS_H\n#include <stdint.h>\n';
let source='/* Generated by tools/generate_media_bindings.mjs. */\n#include "media_bindings.h"\n#include "media_loader.h"\n';
for(const entry of entries) {
 const parameters=Array.from({length:entry.words},(_,i)=>'uintptr_t p'+i).join(',')||'void';
 const types=Array(entry.words).fill('uintptr_t').join(',')||'void';
 const args=Array.from({length:entry.words},(_,i)=>'p'+i).join(',');
 const convention=entry.callback?'__stdcall':'__cdecl';
 const prototype='int '+convention+' '+entry.identifier+'('+parameters+')';
 header+=prototype+';\n';
 source+=prototype+'\n{\n    typedef int (__stdcall *Function)('+types+');\n    Function function=(Function)restore_media_resolve("'+entry.dll+'","'+entry.export+'");\n    return function('+args+');\n}\n';
}
header+='#endif\n';
async function save(relative,content) {
 const filename=path.join(root,relative);
 try {if(await readFile(filename,'utf8')===content) return;} catch(error) {if(error.code!=='ENOENT') throw error;}
 await writeFile(filename,content);
}
await save('include/media_bindings.h',header);
await save('runtime/media_bindings.c',source);
await save('metadata/media-bindings.json',JSON.stringify({format:1,original_executable_required:false,entries},null,2)+'\n');
// Offline contract test: real forwarding code, a synthetic stdcall export for
// every signature, and exact DLL/name/argument observations. No DLL is loaded.
let test='#include "media_bindings.h"\n#include "media_loader.h"\n#include <string.h>\n#include <stdio.h>\n#include <stdlib.h>\nstatic unsigned int expected,seen,resolutions;\n';
const value=i=>`(uintptr_t)(0x89abcdefu ^ (${i}u * 0x1020304u))`;
entries.forEach((entry,index)=>{
 const params=Array.from({length:entry.words},(_,i)=>'uintptr_t p'+i).join(',')||'void';
 test+=`static int __stdcall fixture${index}(${params})\n{\n if(expected!=${index}u) abort();\n`;
 for(let i=0;i<entry.words;i++) test+=` if(p${i}!=${value(i)}) abort();\n`;
 test+=` ++seen; return (int)(0xa9870000u+${index}u);\n}\n`;
});
test+='FARPROC restore_media_resolve(const char *dll,const char *name)\n{\n ++resolutions;\n switch(expected) {\n';
entries.forEach((entry,index)=>{test+=` case ${index}: if(strcmp(dll,"${entry.dll}")||strcmp(name,"${entry.export}")) abort(); return (FARPROC)fixture${index};\n`;});
test+=' default: abort();\n }\n}\nint main(void)\n{\n unsigned int iteration;\n for(iteration=0;iteration<1000;++iteration) {\n';
entries.forEach((entry,index)=>{test+=` expected=${index}; if(${entry.identifier}(${Array.from({length:entry.words},(_,i)=>value(i)).join(',')})!=(int)(0xa9870000u+${index}u)) return 1;\n`;});
test+=` }\n if(seen!=${entries.length*1000}u||resolutions!=seen) return 2;\n puts("60 multimedia forwarding signatures, raw argument bits, return values and stack cleanup verified.");\n return 0;\n}\n`;
await save('tests/media_bindings.c',test);
console.log('Generated '+entries.length+' real DLL export bindings.');
